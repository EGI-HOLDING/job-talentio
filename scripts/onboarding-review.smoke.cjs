const assert = require('node:assert/strict');
const { employeeOnboardingSchema, resumeImportSchema } = require('../packages/shared/dist');
const { createReview, selectedReview, reviewError } = require('./lib/load-onboarding-review.cjs')();
const parsed = require('./fixtures/incomplete-onboarding-cv.cjs');
const review = createReview(parsed);
assert.equal(review.data.experiences.length, 10, 'incomplete parser rows remain editable');
assert.equal(review.experiences.filter(Boolean).length, 7, 'only complete experiences are selected by default');
const payload = { step: 5, reviewState: review, review: null };
assert.ok(employeeOnboardingSchema.safeParse(payload).success, 'draft autosave accepts unknown job titles');
assert.equal(reviewError(selectedReview(review)), null);
assert.equal(selectedReview(review).experiences.length, 7);
const incomplete = structuredClone(review); incomplete.experiences[0] = true;
assert.equal(reviewError(selectedReview(incomplete)), 'missingExperience');
assert.equal(employeeOnboardingSchema.safeParse({ ...payload, review: selectedReview(incomplete) }).success, false, 'final import still rejects an empty title');
const editing = structuredClone(review); editing.data.skills[0] = ''; editing.data.educations[0].school = '';
assert.ok(employeeOnboardingSchema.safeParse({ ...payload, reviewState: editing }).success, 'clearing selected fields during editing does not break draft persistence');
assert.equal(reviewError(selectedReview(editing)), 'reviewRequiredData');
editing.skills[0] = false; editing.educations[0] = false;
assert.equal(reviewError(selectedReview(editing)), null, 'excluded incomplete rows never enter import payload');
assert.equal(reviewError(selectedReview(incomplete, true)), null, 'no-experience choice does not import experience rows');
assert.equal(selectedReview(incomplete, true).experiences.length, 0);
const repaired = structuredClone(incomplete); repaired.data.experiences[0].title = 'Reviewed engineer';
assert.equal(reviewError(selectedReview(repaired)), null); assert.equal(selectedReview(repaired).experiences.length, 8);
assert.equal(resumeImportSchema.safeParse({ experiences: [{ title: '  ', companyName: 'Example' }] }).success, false);
assert.equal(createReview({ experiences: [{ title: 'Engineer', companyName: 'Example' }] }).experiences[0], false, 'missing dates are not invented or imported');
console.log('PASS onboarding CV review: partial drafts autosave, 3 incomplete roles deselected, strict final import, editing/reload exclusions and no fabricated dates');

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { createRequire } = require('node:module');
const req = createRequire(path.resolve('apps/api/package.json'));
const db = new (req('@prisma/client').PrismaClient)();
assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(new URL(process.env.DATABASE_URL).hostname));
const marker = `scoring-audit-${Date.now()}`;
const userIds = [], companyIds = [], storageKeys = [], checks = [];
async function http(route, session, method = 'GET', body, status = 200, locale = 'en') {
  const response = await fetch('http://localhost:4000/api' + route, { method, headers: { 'X-Locale': locale, ...(session ? { Authorization: `Bearer ${session.accessToken}` } : {}), ...(body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, body: body ? body instanceof FormData ? body : JSON.stringify(body) : undefined });
  const result = await response.json();
  assert.equal(response.status, status, `${method} ${route}: ${JSON.stringify(result)}`);
  return result;
}
async function register(role, suffix) {
  const session = await http('/auth/register', null, 'POST', { email: `${marker}-${suffix}@example.test`, password: 'Local-employer-audit-2026!', fullName: `${marker} ${suffix}`, role, locale: 'en', acceptTerms: true, ...(role === 'RECRUITER' ? { companyName: `${marker} ${suffix}` } : {}) }, 201);
  userIds.push(session.user.id);
  if (role === 'RECRUITER') companyIds.push(...session.user.memberships.map(member => member.companyId));
  return session;
}
async function main() {
  const employee = await register('EMPLOYEE', 'target');
  const employer = await register('RECRUITER', 'owner');
  const stranger = await register('RECRUITER', 'stranger');
  const country = await db.country.findFirstOrThrow({ where: { iso2: 'ID', isActive: true } });
  const title = await db.jobTitle.findFirstOrThrow({ where: { name: 'Frontend Developer', archivedAt: null } });
  const skill = await db.skill.findFirstOrThrow({ where: { name: 'React', archivedAt: null } });
  const language = await db.language.findFirstOrThrow({ where: { code: 'en', archivedAt: null } });
  await http('/profiles/me', employee, 'PATCH', { desiredPositions: ['Data Analyst', title.name], preferredCountryIds: [country.id], residenceCountryId: country.id, phone: '+62812345678901' });
  await http('/profiles/me/skills', employee, 'POST', { slug: skill.slug, level: 'EXPERT' }, 201);
  await http('/profiles/me/languages', employee, 'POST', { code: language.code, level: 'NATIVE' }, 201);
  const profile = await db.employeeProfile.findUniqueOrThrow({ where: { userId: employee.user.id } });
  await db.employeeProfile.update({ where: { id: profile.id }, data: { updatedAt: new Date('2001-01-01'), onboardingDraft: { review: { phone: 'PRIVATE_UNREVIEWED_CV_SENTINEL' } } } });
  const job = await db.jobPost.create({ data: { companyId: companyIds[0], jobTitleId: title.id, title: title.name, description: marker, status: 'PUBLISHED', publishedAt: new Date('2001-01-01'), countryId: country.id, workMode: 'REMOTE', jobSkills: { create: { skillId: skill.id, isRequired: true, weight: 1 } }, jobLanguages: { create: { languageId: language.id, minLevel: 'A1', isRequired: true } } } });
  // More than both historical scan caps, all newer than the strong candidate/job.
  const fillerUsers = Array.from({ length: 260 }, (_, index) => ({ id: `audit-${marker}-${index}`, fullName: `${marker} filler ${index}`, email: `${marker}-filler-${index}@example.test`, role: 'EMPLOYEE' }));
  userIds.push(...fillerUsers.map(user => user.id));
  await db.user.createMany({ data: fillerUsers });
  const fillerProfiles = fillerUsers.map(user => ({ id: user.id, userId: user.id, headline: 'Sales Manager', desiredPosition: 'Sales Manager', desiredPositions: ['Sales Manager'], visibility: 'PUBLIC' }));
  await db.employeeProfile.createMany({ data: fillerProfiles });
  await db.profileSkill.createMany({ data: fillerProfiles.map(row => ({ profileId: row.id, skillId: skill.id, level: 'BEGINNER' })) });
  await db.jobPost.createMany({ data: fillerUsers.map(user => ({ companyId: companyIds[0], title: 'Sales Manager', description: marker, status: 'PUBLISHED', publishedAt: new Date(), countryId: country.id, workMode: 'REMOTE' })) });
  const detail = await http(`/jobs/${job.id}`, employee);
  const sum = ['skills', 'title', 'experience', 'location', 'education', 'language'].reduce((total, key) => total + detail.matchBreakdown[key], 0);
  assert.equal(detail.matchScore, sum);
  const employeeList = await http(`/jobs?companySlug=${encodeURIComponent((await db.company.findUniqueOrThrow({ where: { id: companyIds[0] } })).slug)}&sort=match&limit=50`, employee);
  assert.equal(employeeList.truncated, false);
  assert.ok(employeeList.items.some(row => row.id === job.id && row.matchScore === detail.matchScore));
  checks.push('employee match sorting considers the strong older job beyond 250 newer jobs; buckets sum to total');
  const candidates = await http(`/profiles/candidates?q=${marker}&jobTitle=${title.slug}&matchJobId=${job.id}&sort=match`, employer);
  const candidate = candidates.items.find(row => row.id === profile.id);
  assert.ok(candidate, 'The second desired role must pass candidate filtering');
  assert.equal(candidate.matchScore, detail.matchScore);
  assert.ok(!('phone' in candidate));
  assert.ok(!('onboardingDraft' in candidate));
  assert.ok(!JSON.stringify(candidates).includes('PRIVATE_UNREVIEWED_CV_SENTINEL'));
  const recommendations = await http(`/jobs/${job.id}/recommended-candidates`, employer);
  assert.ok(recommendations.some(row => row.profile.id === profile.id && row.matchScore === detail.matchScore));
  checks.push('employer role filtering includes every desired role; recommendations scan beyond 200 weak candidates; scores agree');
  checks.push('candidate search excludes phone and unreviewed CV draft');
  const secondarySearch = await http(`/profiles/candidates?q=${encodeURIComponent('frontend developer')}&matchJobId=${job.id}`, employer);
  assert.ok(secondarySearch.items.some(row => row.id === profile.id), 'Free-text search must include secondary desired roles case-insensitively');
  await db.employeeProfile.update({ where: { id: profile.id }, data: { desiredPosition: null, desiredPositions: [], headline: title.name, contentLocale: 'en' } });
  await db.employeeProfileTranslation.create({ data: { profileId: profile.id, locale: 'id', headline: 'Sales Manager', isMachine: false } });
  const translatedSearch = await http(`/profiles/candidates?q=${marker}&matchJobId=${job.id}&sort=match`, employer, 'GET', undefined, 200, 'id');
  const translatedCandidate = translatedSearch.items.find(row => row.id === profile.id);
  assert.equal(translatedCandidate.headline, 'Sales Manager');
  assert.equal(translatedCandidate.matchScore, detail.matchScore, 'Display translation cannot alter scoring');
  checks.push('display translations do not alter canonical scoring or title filtering');
  await db.employeeProfile.update({ where: { id: profile.id }, data: { visibility: 'PRIVATE' } });
  assert.ok(!(await http(`/jobs/${job.id}/recommended-candidates`, employer)).some(row => row.profile.id === profile.id));
  await http(`/profiles/candidates/${profile.id}?matchJobId=${job.id}`, employer, 'GET', undefined, 404);
  await db.employeeProfile.update({ where: { id: profile.id }, data: { visibility: 'PUBLIC' } });
  await http(`/profiles/candidates?matchJobId=${job.id}`, stranger, 'GET', undefined, 403);
  await http(`/jobs/${job.id}/recommended-candidates`, stranger, 'GET', undefined, 403);
  checks.push('private candidates and another company\'s job-scoring endpoints remain inaccessible');
  const pdfBytes = fs.readFileSync('node_modules/.cache/employee-onboarding/fixtures/employee-cv.pdf');
  const form = new FormData(); form.append('file', new Blob([pdfBytes], { type: 'application/pdf' }), 'original.pdf');
  const resume = await http('/profiles/me/resumes/upload', employee, 'POST', form, 201);
  const originalKey = (await db.resume.findUniqueOrThrow({ where: { id: resume.id } })).fileKey;
  storageKeys.push(originalKey);
  const yesNo = await db.jobQuestion.create({ data: { jobPostId: job.id, question: 'Are you available?', type: 'YES_NO', isRequired: true } });
  const numeric = await db.jobQuestion.create({ data: { jobPostId: job.id, question: 'Years?', type: 'NUMBER', isRequired: true } });
  const answers = [{ questionId: yesNo.id, answer: 'Yes' }, { questionId: numeric.id, answer: '0' }];
  for (const invalid of [[], [{ questionId: 'foreign-question', answer: 'Yes' }], [answers[0], answers[0], answers[1]], [{ ...answers[0], answer: 'maybe' }, answers[1]], [answers[0], { ...answers[1], answer: 'Infinity' }]]) {
    await http(`/applications/jobs/${job.id}`, employee, 'POST', { resumeId: resume.id, answers: invalid }, 400);
    assert.equal(await db.application.count({ where: { jobPostId: job.id } }), 0);
  }
  const application = await http(`/applications/jobs/${job.id}`, employee, 'POST', { resumeId: resume.id, answers }, 201);
  const assertPrivate = value => { const json = JSON.stringify(value); for (const key of ['fileKey', 'fileUrl', 'parsedData', 'PRIVATE_UNREVIEWED_CV_SENTINEL']) assert.ok(!json.includes(key), `Private field leaked: ${key}`); };
  assertPrivate(application);
  assertPrivate(await http('/applications/mine', employee));
  await http(`/applications/jobs/${job.id}`, employee, 'POST', { resumeId: resume.id, answers }, 409);
  assert.equal(await db.application.count({ where: { jobPostId: job.id } }), 1);
  assert.equal(await db.pipelineEvent.count({ where: { applicationId: application.id } }), 1);
  checks.push('invalid, duplicated or foreign screening answers roll back; numeric zero accepted; repeat submission cannot duplicate application/event; payload hides storage/parser internals');
  assert.equal(application.matchScore, detail.matchScore);
  const replace = new FormData(); replace.append('file', new Blob([fs.readFileSync('node_modules/.cache/employee-onboarding/fixtures/employee-cv.docx')], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }), 'replacement.docx');
  await http(`/profiles/me/resumes/${resume.id}/file`, employee, 'POST', replace, 201);
  storageKeys.push((await db.resume.findUniqueOrThrow({ where: { id: resume.id } })).fileKey);
  const download = await http(`/applications/${application.id}/resume-download`, employer);
  assert.ok(decodeURIComponent(new URL(download.url).pathname).endsWith(originalKey));
  const libraryDownload = await http(`/profiles/resumes/${resume.id}/download`, employer);
  assert.ok(decodeURIComponent(new URL(libraryDownload.url).pathname).endsWith(originalKey));
  const fileResponse = await fetch(download.url);
  assert.ok(fileResponse.ok);
  assert.ok(Buffer.from(await fileResponse.arrayBuffer()).equals(pdfBytes));
  await http(`/applications/${application.id}/resume-download`, stranger, 'GET', undefined, 403);
  const pipeline = await http(`/applications/jobs/${job.id}`, employer);
  assertPrivate(pipeline);
  await http(`/applications/${application.id}/rescore`, stranger, 'POST', {}, 403);
  await db.employeeProfile.update({ where: { id: profile.id }, data: { headline: 'Sales Manager' } });
  const updatedLive = await http(`/jobs/${job.id}`, employee);
  assert.ok(updatedLive.matchScore < detail.matchScore);
  assert.equal((await http('/applications/mine', employee)).find(row => row.id === application.id).matchScore, detail.matchScore, 'Submitted score is a snapshot until explicit rescore');
  const rescored = await http(`/applications/${application.id}/rescore`, employer, 'POST', {}, 201);
  assertPrivate(rescored);
  assert.equal(rescored.matchScore, updatedLive.matchScore);
  assert.equal((await http('/applications/mine', employee)).find(row => row.id === application.id).matchScore, updatedLive.matchScore);
  checks.push('live discovery scores follow profile changes; application scores retain submission snapshot until explicit rescore, then both sides agree');
  await http(`/applications/${application.id}/status`, stranger, 'POST', { status: 'IN_REVIEW' }, 403);
  await http(`/applications/${application.id}/interviews`, stranger, 'POST', { scheduledAt: new Date(Date.now() + 86400000).toISOString() }, 403);
  assertPrivate(await http(`/applications/${application.id}/status`, employee, 'POST', { status: 'WITHDRAWN' }, 201));
  assertPrivate(await http(`/applications/${application.id}/status`, employee, 'POST', { status: 'WITHDRAWN' }, 201));
  await http(`/applications/${application.id}/status`, employer, 'POST', { status: 'IN_REVIEW' }, 400);
  await http(`/applications/${application.id}/interviews`, employer, 'POST', { scheduledAt: new Date(Date.now() + 86400000).toISOString() }, 400);
  checks.push('cross-company rescore/status/interview denied; withdrawn applications cannot reopen or receive interviews; retry does not disclose internal fields');
  assert.ok(!JSON.stringify(pipeline).includes('PRIVATE_UNREVIEWED_CV_SENTINEL'));
  checks.push('application and generic recruiter downloads retain submitted CV bytes after replacement; old employer cannot access new CV');
  console.log(JSON.stringify({ result: 'PASS', checks }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await db.company.deleteMany({ where: { id: { in: companyIds } } });
  await db.user.deleteMany({ where: { id: { in: userIds } } });
  if (storageKeys.length) {
    const { execFileSync } = require('node:child_process');
    const info = JSON.parse(execFileSync('docker', ['inspect', 'jt-minio'], { encoding: 'utf8', windowsHide: true }))[0];
    const env = Object.fromEntries(info.Config.Env.map(value => { const at = value.indexOf('='); return [value.slice(0, at), value.slice(at + 1)]; }));
    const { S3Client, DeleteObjectCommand } = req('@aws-sdk/client-s3');
    const storage = new S3Client({ endpoint: `http://127.0.0.1:${info.NetworkSettings.Ports['9000/tcp'][0].HostPort}`, region: 'us-east-1', forcePathStyle: true, credentials: { accessKeyId: env.MINIO_ROOT_USER, secretAccessKey: env.MINIO_ROOT_PASSWORD } });
    for (const Key of storageKeys) await storage.send(new DeleteObjectCommand({ Bucket: 'job-talentio', Key }));
    storage.destroy();
  }
  await db.$disconnect();
});

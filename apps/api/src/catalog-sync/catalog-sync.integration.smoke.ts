import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { applySnapshot, assertStaging, canonical, inspectPlan, quote, readSnapshot, TABLES, validateSnapshot } from './catalog-sync';
import { backfillJobTitles } from '../common/job-title-backfill';
import { jobFingerprint } from '../common/dedupe';

async function main() {
  const url = new URL(process.env.DATABASE_URL || '');
  assert.ok(['localhost', '127.0.0.1'].includes(url.hostname) && url.port === '5434', 'Only the local fixture server is allowed');
  const snapshot = JSON.parse(readFileSync(process.argv[2], 'utf8'));
  validateSnapshot(snapshot);
  const altered = structuredClone(snapshot); altered.tables.JobTitle.rows[0].name += ' tampered';
  assert.throws(() => validateSnapshot(altered), /checksum/);
  assert.throws(() => assertStaging({ RAILWAY_ENVIRONMENT_NAME: 'production' }), /approved Railway staging/);
  const oldMode = process.env.CATALOG_SOURCE_MODE; process.env.CATALOG_SOURCE_MODE = 'database';
  assert.equal((await backfillJobTitles(new Proxy({}, { get() { throw Error('Backfill touched the database'); } }) as never)).updated, 0);
  if (oldMode === undefined) delete process.env.CATALOG_SOURCE_MODE; else process.env.CATALOG_SOURCE_MODE = oldMode;
  const name = 'jt_catalog_sync_test_' + Date.now();
  assert.match(name, /^jt_catalog_sync_test_\d+$/);
  const admin = new PrismaClient();
  const targetUrl = new URL(url); targetUrl.pathname = '/' + name;
  const target = new PrismaClient({ datasources: { db: { url: targetUrl.toString() } } });
  try {
    const dump = execFileSync('docker', ['exec', 'jt-postgres', 'pg_dump', '-U', 'talentio', '-d', 'talentio_hr_demo', '--format=custom', '--no-owner', '--no-acl'], { maxBuffer: 100 * 1024 * 1024, windowsHide: true });
    await admin.$executeRawUnsafe('CREATE DATABASE ' + quote(name));
    execFileSync('docker', ['exec', '-i', 'jt-postgres', 'pg_restore', '-U', 'talentio', '-d', name, '--no-owner', '--no-acl', '--exit-on-error'], { input: dump, maxBuffer: 1024 * 1024, windowsHide: true });
    assert.equal((await readSnapshot(target, 'restored')).sha256, snapshot.sha256, 'Backup restores all catalog fields exactly');
    for (const table of TABLES) await target.$executeRawUnsafe('UPDATE ' + quote(table) + " SET id='fixture:'||id");
    const job = await target.jobPost.findFirstOrThrow(), profile = await target.employeeProfile.findFirstOrThrow();
    const province = await target.province.findFirstOrThrow();
    const extraCity = await target.city.create({ data: { id: 'fixture-extra-city', name: 'Unlisted staging city', slug: 'fixture-extra-city', provinceId: province.id } });
    const extraTitle = await target.jobTitle.create({ data: { id: 'fixture-extra-title', name: 'Unlisted staging occupation', slug: 'fixture-extra-title', normalizedKey: 'fixture-extra-title' } });
    const extraLanguage = await target.language.create({ data: { id: 'fixture-extra-language', name: 'Unlisted staging language', code: 'fixture-zz', normalizedKey: 'fixture-zz' } });
    await target.profileLanguage.create({ data: { profileId: profile.id, languageId: extraLanguage.id, level: 'B1' } });
    await target.jobPost.update({ where: { id: job.id }, data: { cityId: extraCity.id, jobTitleId: extraTitle.id } });
    const localTitles = snapshot.tables.JobTitle.rows.filter((r: any) => !r.archivedAt);
    const ambiguous = await target.jobTitle.create({ data: { name: localTitles[0].name, slug: 'fixture-ambiguous', normalizedKey: 'fixture-ambiguous' } });
    await target.jobTitleAlias.create({ data: { jobTitleId: ambiguous.id, alias: localTitles[1].name, aliasKey: 'fixture-ambiguous-alias' } });
    const ambiguousPlan = await inspectPlan(target, snapshot);
    assert.ok(ambiguousPlan.conflicts.some(c => c.includes('Ambiguous JobTitle:' + ambiguous.id)));
    await assert.rejects(applySnapshot(target, snapshot, ambiguousPlan.planHash), /Resolve dry-run conflicts/);
    await target.jobTitle.delete({ where: { id: ambiguous.id } });
    const existingSkill = await target.profileSkill.findFirstOrThrow({ where: { profileId: profile.id }, include: { skill: true } });
    const duplicateSkill = await target.skill.create({ data: { name: existingSkill.skill.name, slug: 'fixture-duplicate-skill', normalizedKey: 'fixture-duplicate-skill' } });
    await target.profileSkill.create({ data: { profileId: profile.id, skillId: duplicateSkill.id, level: existingSkill.level === 'EXPERT' ? 'BEGINNER' : 'EXPERT', levelSource: 'USER_CONFIRMED' } });
    const conflictPlan = await inspectPlan(target, snapshot);
    assert.ok(conflictPlan.conflicts.some(c => c.includes('Conflicting relation payload: ProfileSkill')));
    await assert.rejects(applySnapshot(target, snapshot, conflictPlan.planHash), /Resolve dry-run conflicts/);
    await target.skill.delete({ where: { id: duplicateSkill.id } });
    const plan = await inspectPlan(target, snapshot);
    assert.deepEqual(plan.conflicts, []);
    assert.ok(plan.detached['ProfileLanguage.languageId'] > 0);
    const before = await readSnapshot(target, 'before');
    await assert.rejects(applySnapshot(target, snapshot, plan.planHash, 'after-delete'), /Injected rollback/);
    assert.equal((await readSnapshot(target, 'rollback')).sha256, before.sha256, 'Fault rolls back rows and constraint DDL');
    const stale = await target.skill.create({ data: { name: 'Stale target fixture', slug: 'fixture-stale-skill', normalizedKey: 'fixture-stale-skill' } });
    await assert.rejects(applySnapshot(target, snapshot, plan.planHash), /Target changed/);
    await target.skill.delete({ where: { id: stale.id } });
    const current = await inspectPlan(target, snapshot);
    const result = await applySnapshot(target, snapshot, current.planHash);
    assert.equal(result.verified, true);
    assert.equal((await readSnapshot(target, 'after')).sha256, snapshot.sha256);
    const updated = await target.jobPost.findUniqueOrThrow({ where: { id: job.id } });
    assert.equal(updated.cityId, null); assert.equal(updated.jobTitleId, null);
    assert.equal(updated.title, job.title); assert.equal(updated.fingerprint, jobFingerprint(updated));
    assert.equal(await target.profileLanguage.count({ where: { languageId: extraLanguage.id } }), 0);
    assert.ok(await target.employeeProfile.findUnique({ where: { id: profile.id } }));
    const repeated = await inspectPlan(target, snapshot);
    assert.ok(Object.values(repeated.tableChanges).every(t => t.equal));
    assert.deepEqual(repeated.conflicts, []);
    assert.equal((await applySnapshot(target, snapshot, repeated.planHash)).applied, false);
    assert.equal(canonical(repeated.changes), '{}');
    console.log('PASS catalog sync: exact backup restore, ID remapping, detached references, timestamps/JSON/aliases, ambiguity and payload conflicts, stale target rejection, transactional rollback, protected records, idempotency and database-owned startup.');
  } finally {
    await target.$disconnect();
    await admin.$executeRawUnsafe('DROP DATABASE IF EXISTS ' + quote(name) + ' WITH (FORCE)');
    await admin.$disconnect();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });

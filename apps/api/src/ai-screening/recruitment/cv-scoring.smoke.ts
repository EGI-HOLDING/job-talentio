import assert from 'node:assert/strict';
import { CV_MAX_BYTES, CV_RUBRIC, validateCvResult, validateCvBytes, fileChecksum } from './cv-scoring.policy';
import { candidateImportSchema, candidateListSchema } from './recruitment.schemas';
import { composePrompt } from '../prompts/compose';
import { assertSchema } from '../screening.schemas';
const cvText = 'Dinda Pramesti\nMengembangkan API Node.js selama 4 tahun.\nMembantu tim menjalankan layanan pelanggan.';
const sample = { readable: true, fullName: 'Dinda Pramesti', email: null, phone: null, headline: 'Backend Developer', summary: 'Pengalaman API.', cvText,
  criteria: CV_RUBRIC.map(c => ({ criterionId: c.id, level: 3, reason: 'Bukti relevan tersedia.', evidence: ['Mengembangkan API Node.js selama 4 tahun.'] })), limitations: [] };
assert.equal(validateCvResult(sample, true).score, 75);
assert.equal(validateCvResult({ ...sample, criteria: sample.criteria.map((c,i) => ({ ...c, level: [4,2,0][i] })) }, true).score, 57.5);
assert.equal(validateCvResult({ ...sample, criteria: [] }, false).score, null);
assert.throws(() => validateCvResult({ ...sample, criteria: [] }, true));
assert.throws(() => validateCvResult({ ...sample, criteria: [...sample.criteria.slice(0,2), sample.criteria[0]] }, true));
assert.throws(() => validateCvResult({ ...sample, criteria: sample.criteria.map(c => ({ ...c, criterionId: 'attacker' })) }, true));
assert.throws(() => validateCvResult({ ...sample, criteria: sample.criteria.map(c => ({ ...c, level: 5 })) }, true));
assert.throws(() => validateCvResult({ ...sample, criteria: sample.criteria.map(c => ({ ...c, evidence: ['Memimpin 30 engineer.'] })) }, true));
assert.throws(() => validateCvResult({ ...sample, criteria: sample.criteria.map(c => ({ ...c, evidence: [] })) }, true));
assert.throws(() => validateCvResult({ ...sample, cvText: '' }, true));
assert.equal(validateCvResult({ ...sample, readable: false, cvText: '', criteria: [] }, true).score, null);
assert.equal(validateCvBytes(Buffer.from('%PDF-1.4 data'), 'cv.pdf'), 'application/pdf');
assert.throws(() => validateCvBytes(Buffer.from('<script>bad</script>'), 'cv.pdf'));
assert.throws(() => validateCvBytes(Buffer.from('%PDF-1.4'), 'cv.exe'));
assert.throws(() => validateCvBytes(Buffer.alloc(0), 'cv.pdf'), /CV_FILE_SIZE/);
assert.throws(() => validateCvBytes(Buffer.from('%PDF-1.4 data'), 'cv.docx'), /CV_FILE_INVALID/);
const maxSizePdf = Buffer.alloc(CV_MAX_BYTES);
maxSizePdf.write('%PDF-');
assert.equal(validateCvBytes(maxSizePdf, 'cv.pdf'), 'application/pdf');
assert.throws(() => validateCvBytes(Buffer.concat([maxSizePdf, Buffer.alloc(1)]), 'cv.pdf'), /CV_FILE_SIZE/);
assert.equal(fileChecksum(Buffer.from('same')), fileChecksum(Buffer.from('same')));
const prompt=composePrompt('cv-score', {job:{title:'Developer'}});
assertSchema(prompt.schema,sample);
for (const rule of ['tidak tepercaya','usia','gender','bukan verifikasi','skor saya 100']) assert.ok(prompt.instructions.includes(rule),rule);
assert.ok(!prompt.instructions.includes('gue/lu'), 'CV assessment has no conversational humor');
const file={clientId:'f1',filename:'cv.pdf',size:100,contentType:'application/pdf'};
assert.throws(()=>candidateImportSchema.parse({companyId:'co',requestKey:'request-0001',files:[file,file]}));
assert.throws(()=>candidateImportSchema.parse({companyId:'co',requestKey:'request-0001',files:[{...file,size:99999999}]}));
assert.equal(candidateListSchema.parse({companyId:'co'}).limit,10);
assert.throws(()=>candidateListSchema.parse({companyId:'co',limit:10001}));
console.log('CV scoring: grounding, weighted arithmetic, invalid provider output, file and import validation passed.');
